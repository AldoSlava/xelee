#!/usr/bin/env python3
"""Generate src/melee/mn/mnstagesel_frozen.h: the "Frozen" caption for the
stage select's Pokemon Stadium name (Slippi Direct's Frozen Stadium toggle).

The vanilla name texture carries the caption "Kanto" in a light serif; Slippi
ships a patched texture reading "Frozen". We draw our own: Noto Serif Regular
(SIL Open Font License), 16 pt with 1.2 px extra tracking, which renders
"Kanto" at the vanilla caption's exact 50x12 box. The game pastes this over
the caption rows of the vanilla frame at runtime (mnstagesel_slippi.c).

Needs ImageMagick (`magick`) and the font file.
"""
import subprocess
import sys

FONT = "/usr/share/fonts/google-noto/NotoSerif-Regular.ttf"
OUT = "src/melee/mn/mnstagesel_frozen.h"


def main():
    font = sys.argv[1] if len(sys.argv) > 1 else FONT
    args = ["magick", "-background", "black", "-fill", "white", "-font", font, "-pointsize", "16",
            "-kerning", "1.2", "label:Frozen", "-trim"]
    size = subprocess.run(args + ["info:"], capture_output=True, text=True, check=True).stdout.split()[2]
    w, h = map(int, size.split("x"))
    raw = subprocess.run(args + ["-depth", "8", "gray:-"], capture_output=True, check=True).stdout
    assert len(raw) == w * h, (len(raw), w, h)
    lines = [
        "/* Generated by tools/gen_sss_frozen.py: \"Frozen\" in Noto Serif Regular",
        " * (SIL Open Font License), 8-bit coverage, row-major. */",
        "#define SSS_FROZEN_W %d" % w,
        "#define SSS_FROZEN_H %d" % h,
        "static const unsigned char sss_frozen_caption[SSS_FROZEN_W * SSS_FROZEN_H] = {",
    ]
    for y in range(h):
        row = raw[y * w:(y + 1) * w]
        lines.append("    " + ", ".join("%d" % v for v in row) + ",")
    lines.append("};")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("wrote %s (%dx%d)" % (OUT, w, h))


if __name__ == "__main__":
    main()
