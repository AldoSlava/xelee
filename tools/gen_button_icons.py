#!/usr/bin/env python3
"""Render the GameCube button icons in assets/button_icons/*.svg to 64x64 GX
RGBA8 textures and write src/pc/button_icons_data.c.

The icons are SmashWiki's (https://www.ssbwiki.com/Category:Button_icons_(GCN)),
CC BY-SA 4.0; see assets/button_icons/README.md. Needs ImageMagick with its
SVG renderer. Run from the repository root:  tools/gen_button_icons.py
"""
import subprocess, sys, os

SIZE = 64
NAMES = ["L", "R", "Y", "Z"]

def render(name):
    raw = subprocess.run(
        ["magick", "-background", "none", "-density", "96",
         f"assets/button_icons/{name}.svg", "-resize", f"{SIZE}x{SIZE}",
         "-gravity", "center", "-extent", f"{SIZE}x{SIZE}",
         "-depth", "8", "rgba:-"], check=True, capture_output=True).stdout
    assert len(raw) == SIZE * SIZE * 4
    return raw

def gx_rgba8(raw):
    """GX RGBA8: 4x4 texel tiles, each 64 bytes: the 16 texels' A,R pairs then
    their G,B pairs."""
    out = bytearray()
    for ty in range(0, SIZE, 4):
        for tx in range(0, SIZE, 4):
            ar, gb = bytearray(), bytearray()
            for y in range(4):
                for x in range(4):
                    i = ((ty + y) * SIZE + tx + x) * 4
                    r, g, b, a = raw[i:i + 4]
                    ar += bytes([a, r])
                    gb += bytes([g, b])
            out += ar + gb
    return bytes(out)

lines = ['/* Generated by tools/gen_button_icons.py from assets/button_icons/*.svg.',
         ' * SmashWiki button icons, CC BY-SA 4.0 (see assets/button_icons/README.md). */',
         '#include "pc/button_icons.h"', '']
for n in NAMES:
    raw = render(n)
    data = gx_rgba8(raw)
    lines.append(f'static const unsigned char icon_{n}[{len(data)}] __attribute__((aligned(32))) = {{')
    for i in range(0, len(data), 24):
        lines.append('    ' + ','.join(str(b) for b in data[i:i + 24]) + ',')
    lines.append('};')
    lines.append('')
lines.append('const unsigned char* const pc_button_icon_data[PC_BUTTON_ICON_COUNT] = {')
for n in NAMES:
    lines.append(f'    icon_{n},')
lines.append('};')
open('src/pc/button_icons_data.c', 'w').write('\n'.join(lines) + '\n')
print('wrote src/pc/button_icons_data.c')
